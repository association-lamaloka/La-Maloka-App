import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const upload = readFileSync(new URL('../api/media/upload.ts', import.meta.url), 'utf8');
const drive = readFileSync(new URL('../api/media/drive.ts', import.meta.url), 'utf8');
const rules = readFileSync(new URL('../firestore.rules', import.meta.url), 'utf8');
const env = readFileSync(new URL('../.env.example', import.meta.url), 'utf8');
const uploader = readFileSync(new URL('../src/components/MediaUploader.tsx', import.meta.url), 'utf8');
const admin = readFileSync(new URL('../src/components/SimpleAdmin.tsx', import.meta.url), 'utf8');
assert.match(upload, /request\.headers\.authorization/, 'Le endpoint doit exiger un Firebase ID token.');
assert.match(upload, /accounts:lookup/, 'Le token doit être vérifié côté serveur auprès de Firebase Auth.');
assert.match(upload, /association\.lamaloka@gmail\.com/, 'Seul le compte officiel est autorisé.');
assert.match(upload, /emailVerified === true/, 'Le courriel doit être vérifié.');
for (const mime of ['image/jpeg','image/png','image/webp','image/avif']) assert.match(upload, new RegExp(mime.replace('/','\\/')));
assert.match(upload, /BLOB_READ_WRITE_TOKEN/, 'Le secret Blob doit venir exclusivement de l’environnement serveur.');
assert.match(upload, /import \{ put \} from '@vercel\/blob'/, 'Le endpoint doit utiliser le SDK officiel Vercel Blob.');
assert.match(upload, /put\(pathname, body, \{ access: 'public', contentType, token: blobToken/, 'Le Buffer validé doit être envoyé au Blob public avec le token serveur.');
assert.doesNotMatch(upload, /blob\.vercel-storage\.com/, 'Aucun appel REST Blob manuel ne doit subsister.');
assert.doesNotMatch(upload, /VITE_BLOB|NEXT_PUBLIC/, 'Le secret ne doit jamais être public.');
assert.match(drive, /\^\[A-Za-z0-9_-\]\{20,100\}\$/, 'Le fileId Drive doit être strictement validé.');
assert.match(rules, /match \/navigation\/{id}/);
assert.match(rules, /driveFileId\.matches\('\^\[A-Za-z0-9_-\]\{20,100\}\$'\)/);
assert.match(env, /^BLOB_READ_WRITE_TOKEN=$/m);
assert.match(uploader, /5 \* 1024 \* 1024/, 'Le navigateur doit refuser les images de plus de 5 Mo.');
assert.match(uploader, /const previousUrl = currentUrl \|\| ''/, 'L’URL antérieure doit être capturée avant la mise en ligne.');
assert.match(uploader, /setPreview\(previousUrl\)/, 'Un échec doit restaurer l’ancienne image.');
assert.match(uploader, /xhr\.timeout = UPLOAD_TIMEOUT_MS/, 'La requête navigateur doit avoir un délai maximal.');
assert.match(uploader, /xhr\.ontimeout/, 'Le dépassement du délai doit être signalé clairement.');
assert.match(uploader, /request\.current\?\.abort\(\)/, 'La requête active doit pouvoir être annulée.');
assert.match(uploader, /Image mise en ligne avec succès/, 'La réussite doit être confirmée dans l’interface.');
assert.match(uploader, /onUploaded\(result\)/, 'La réponse Blob doit mettre à jour automatiquement le champ URL.');
for (const label of ['Image principale','Logotype','Image de la carte superposée','Image du cours','Image de l’événement','Logotype général']) assert.match(admin, new RegExp(label));
assert.doesNotMatch(admin, /MediaUploader[^\n]+save(?:HomePage|Course|Event|SiteSettings)/, 'La mise en ligne ne doit pas enregistrer Firestore directement.');
console.log('Médias vérifiés : token Firebase, admin vérifié, formats, taille, Blob serveur, Drive et règles.');
